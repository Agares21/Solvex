// Solo desarrollo: conserva proveedores, productos, compras y movimientos propios de prueba.
import assert from 'node:assert/strict';
const base = process.env.SOLVEX_TEST_API_URL?.replace(/\/$/, '');
if (!base) throw new Error('Define SOLVEX_TEST_API_URL para una API de desarrollo migrada.');
async function send(path, method = 'GET', body, expected = 200) {
  const response = await fetch(`${base}${path}`, { method, headers: { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
  const text = await response.text();
  assert.equal(response.status, expected, `${method} ${path}: ${text}`);
  return { response, data: text ? JSON.parse(text) : undefined };
}
const key = Date.now();
const supplierInput = { identifier: `HTTP-${key}`, name: `Proveedor HTTP ${key}`, contactName: 'Contacto de prueba', phone: '+591 77777777', email: 'proveedor@example.com', address: 'Dirección de prueba' };
const supplier = await send('/suppliers', 'POST', supplierInput, 201);
assert.ok(supplier.response.headers.get('location')?.endsWith(`/suppliers/${supplier.data.id}`));
assert.equal((await send(`/suppliers/${supplier.data.id}`)).data.identifier, supplierInput.identifier);
assert.ok((await send(`/suppliers?search=${key}`)).data.some(s => s.id === supplier.data.id));
assert.equal((await send(`/suppliers?search=${encodeURIComponent(supplierInput.name)}`)).data.length, 1);
await send('/suppliers', 'POST', supplierInput, 409);
await send('/suppliers', 'POST', { identifier: `INVALID-${key}`, name: 'Sin contacto' }, 400);
await send('/suppliers', 'POST', { ...supplierInput, identifier: `INVALID-${key}`, email: 'invalido' }, 400);
await send('/suppliers/2147483647', 'GET', undefined, 404);
const first = (await send('/products', 'POST', { code: `HTTP-A-${key}`, name: 'Producto compra A', price: 10 }, 201)).data;
const second = (await send('/products', 'POST', { code: `HTTP-B-${key}`, name: 'Producto compra B', price: 2 }, 201)).data;
const input = { supplierId: supplier.data.id, details: [{ productId: first.id, quantity: 3, unitCost: 2.50 }, { productId: second.id, quantity: 2, unitCost: 1.20 }] };
const created = await send('/purchases', 'POST', input, 201);
const purchase = created.data;
assert.ok(created.response.headers.get('location')?.endsWith(`/purchases/${purchase.id}`));
assert.equal(purchase.status, 'Pending'); assert.equal(purchase.receivedAt, null);
assert.equal(purchase.total, 9.9); assert.deepEqual(purchase.details.map(d => d.subtotal), [7.5, 2.4]);
assert.equal((await send(`/inventory/${first.id}`)).data.stock, 0);
assert.equal((await send(`/purchases/${purchase.id}`)).data.details.length, 2);
const summary = (await send('/purchases')).data.find(p => p.id === purchase.id);
assert.equal(summary.total, 9.9); assert.equal('details' in summary, false);
await send('/purchases', 'POST', { ...input, supplierId: 2147483647 }, 404);
await send('/purchases', 'POST', { ...input, details: [{ productId: 2147483647, quantity: 1, unitCost: 1 }] }, 404);
await send('/purchases', 'POST', { ...input, details: [] }, 400);
await send('/purchases', 'POST', { ...input, details: [{ productId: first.id, quantity: 0, unitCost: 1 }] }, 400);
await send('/purchases', 'POST', { ...input, details: [{ productId: first.id, quantity: 1, unitCost: -1 }] }, 400);
await send('/purchases', 'POST', { ...input, details: [{ productId: first.id, quantity: 1, unitCost: 1.001 }] }, 400);
const responses = await Promise.all([1, 2].map(() => fetch(`${base}/purchases/${purchase.id}/receive`, { method: 'POST' })));
assert.deepEqual(responses.map(r => r.status).sort(), [200, 409]); await Promise.all(responses.map(r => r.text()));
assert.equal((await send(`/inventory/${first.id}`)).data.stock, 3);
assert.equal((await send(`/inventory/${second.id}`)).data.stock, 2);
assert.equal((await send(`/inventory/${first.id}/movements`)).data.length, 1);
assert.equal((await send(`/purchases/${purchase.id}`)).data.status, 'Received');
await send(`/purchases/${purchase.id}/receive`, 'POST', undefined, 409);
await send('/purchases/2147483647/receive', 'POST', undefined, 404);
// Fallo después de la primera entrada: ambos saldos y todo el historial deben permanecer iguales.
const pending = (await send('/purchases', 'POST', input, 201)).data;
await send(`/products/${second.id}/deactivate`, 'PATCH', undefined, 204);
await send(`/purchases/${pending.id}/receive`, 'POST', undefined, 409);
assert.equal((await send(`/purchases/${pending.id}`)).data.status, 'Pending');
assert.equal((await send(`/purchases/${pending.id}`)).data.receivedAt, null);
assert.equal((await send(`/inventory/${first.id}`)).data.stock, 3);
assert.equal((await send(`/inventory/${first.id}/movements`)).data.length, 1);
await send(`/products/${second.id}/activate`, 'PATCH', undefined, 204);
assert.equal((await send(`/purchases/${pending.id}/receive`, 'POST')).data.status, 'Received');
assert.equal((await send(`/inventory/${first.id}`)).data.stock, 6);
assert.equal((await send(`/inventory/${second.id}`)).data.stock, 4);
console.log(`Sprint 2 HTTP OK: proveedores, búsqueda, validaciones, importes, compras, recepción concurrente y rollback. Proveedor ${supplier.data.id}; compras ${purchase.id}, ${pending.id}.`);
