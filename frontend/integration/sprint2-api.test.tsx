import { cleanup, render, screen, within, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { afterEach, expect, it } from 'vitest';
import SuppliersPage from '../src/features/sprint2/SuppliersPage';
import Compras from '../src/features/sprint2/components/compras/Compras';
import { suppliersApi, purchasesApi } from '../src/services/purchasing';
import { products } from '../src/services/products';
import { inventory } from '../src/services/inventory';
afterEach(cleanup);
it('registra proveedor y compra desde React y recibe una sola vez en SQL Server', async () => {
  // Sin mocks: API real sobre una base de desarrollo ya migrada; conserva sus datos propios.
  const key = `UI-${Date.now()}`;
  const user = userEvent.setup();
  const product = await products.create({ code: key, name: `Producto ${key}`, price: 15, description: 'Prueba de integración React/API' });
  const view = render(<SuppliersPage/>);
  await user.click(screen.getByRole('button', { name: /Nuevo proveedor/ }));
  const form = screen.getByRole('dialog', { name: 'Registrar proveedor' });
  await user.type(within(form).getByLabelText('Nombre o razón social *'), `Proveedor ${key}`);
  await user.type(within(form).getByLabelText('Identificador del proveedor *'), key);
  await user.type(within(form).getByLabelText('Teléfono'), '77777777');
  await user.click(within(form).getByRole('button', { name: 'Registrar proveedor' }));
  await screen.findByText('Proveedor registrado correctamente.');
  const supplier = (await suppliersApi.list()).find(s => s.identifier === key)!;
  expect(supplier.id).toBeGreaterThan(0);
  view.unmount();
  const reloaded = render(<SuppliersPage/>);
  await screen.findByText(key);
  await user.type(screen.getByLabelText('Buscar proveedores'), key);
  await user.click(screen.getByRole('button', { name: /Ver detalles/ }));
  expect((await screen.findByRole('dialog', { name: 'Detalle del proveedor' })).textContent).toContain(key);
  reloaded.unmount();
  render(<Compras/>);
  await user.click(screen.getByRole('button', { name: /Nueva compra/ }));
  const purchaseForm = screen.getByRole('dialog', { name: 'Registrar nueva compra' });
  await within(purchaseForm).findByRole('option', { name: `${key} · Proveedor ${key}` });
  await user.selectOptions(within(purchaseForm).getByLabelText('Proveedor *'), String(supplier.id));
  await user.selectOptions(within(purchaseForm).getByLabelText('Producto 1 *'), String(product.id));
  const quantity = within(purchaseForm).getByLabelText('Cantidad 1 *');
  await user.clear(quantity); await user.type(quantity, '5');
  await user.type(within(purchaseForm).getByLabelText('Costo unitario 1 (Bs) *'), '2.50');
  await user.click(within(purchaseForm).getByRole('button', { name: 'Registrar compra' }));
  await screen.findByText(/registrada como pendiente. El stock no cambió/);
  const purchase = (await purchasesApi.list()).find(p => p.supplierId === supplier.id)!;
  expect(purchase.status).toBe('Pending'); expect(purchase.total).toBe(12.50);
  // La lista del servidor se refresca antes de filtrar y abrir el detalle.
  await waitFor(() => expect(screen.queryByText('Cargando compras…')).toBeNull());
  await user.type(screen.getByLabelText('Buscar compras'), key);
  await user.click(screen.getByRole('button', { name: /Ver detalle/ }));
  const detail = await screen.findByRole('dialog', { name: `Detalle de compra COMP-${purchase.id}` });
  await user.click(within(detail).getByRole('button', { name: 'Recibir compra' }));
  await user.click(within(detail).getByRole('button', { name: 'Confirmar recepción' }));
  await screen.findByText('Esta compra ya fue recibida y no puede recibirse nuevamente.');
  expect((await purchasesApi.get(purchase.id)).status).toBe('Received');
  const response = await fetch(`${import.meta.env.VITE_API_BASE_URL}/inventory/${product.id}`);
  expect((await response.json()).stock).toBe(5);
  expect(await inventory.movements(product.id)).toHaveLength(1);
  await expect(purchasesApi.receive(purchase.id)).rejects.toMatchObject({ status: 409 });
  expect(within(detail).queryByRole('button', { name: 'Recibir compra' })).toBeNull();
});
